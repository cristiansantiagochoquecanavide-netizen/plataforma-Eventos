CREATE TABLE grupo_usuario (
    id_grupo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_organizacion BIGINT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_grupo_usuario_organizacion FOREIGN KEY (id_organizacion) REFERENCES organizacion(id_organizacion),
    CONSTRAINT uk_grupo_usuario_id_organizacion UNIQUE (id_grupo, id_organizacion),
    CONSTRAINT uk_grupo_usuario_organizacion_nombre UNIQUE (id_organizacion, nombre),
    CONSTRAINT chk_grupo_usuario_nombre_no_vacio CHECK (nombre <> '')
);

CREATE TABLE grupo_usuario_miembro (
    id_grupo BIGINT NOT NULL,
    id_usuario BIGINT NOT NULL,
    id_organizacion BIGINT NOT NULL,
    PRIMARY KEY (id_grupo, id_usuario),
    CONSTRAINT fk_grupo_usuario_miembro_grupo FOREIGN KEY (id_grupo, id_organizacion) REFERENCES grupo_usuario(id_grupo, id_organizacion),
    CONSTRAINT fk_grupo_usuario_miembro_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario),
    CONSTRAINT fk_grupo_usuario_miembro_membresia FOREIGN KEY (id_usuario, id_organizacion) REFERENCES usuario_organizacion(id_usuario, id_organizacion)
);

CREATE TABLE grupo_usuario_rol (
    id_grupo BIGINT NOT NULL,
    id_rol BIGINT NOT NULL,
    PRIMARY KEY (id_grupo, id_rol),
    CONSTRAINT fk_grupo_usuario_rol_grupo FOREIGN KEY (id_grupo) REFERENCES grupo_usuario(id_grupo),
    CONSTRAINT fk_grupo_usuario_rol_rol FOREIGN KEY (id_rol) REFERENCES rol(id_rol)
);

CREATE INDEX idx_grupo_usuario_organizacion ON grupo_usuario(id_organizacion);
CREATE INDEX idx_grupo_usuario_miembro_usuario ON grupo_usuario_miembro(id_usuario, id_organizacion);
CREATE INDEX idx_grupo_usuario_rol_rol ON grupo_usuario_rol(id_rol);
