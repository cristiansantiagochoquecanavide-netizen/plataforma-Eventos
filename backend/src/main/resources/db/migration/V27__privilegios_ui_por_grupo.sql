CREATE TABLE grupo_componente_ui_privilegio (
    id_privilegio_ui BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_organizacion BIGINT NOT NULL,
    id_grupo BIGINT NOT NULL,
    clave_componente VARCHAR(120) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_grupo_componente_ui_privilegio_organizacion FOREIGN KEY (id_organizacion) REFERENCES organizacion(id_organizacion),
    CONSTRAINT fk_grupo_componente_ui_privilegio_grupo FOREIGN KEY (id_grupo, id_organizacion) REFERENCES grupo_usuario(id_grupo, id_organizacion),
    CONSTRAINT uk_grupo_componente_ui_privilegio_estado UNIQUE (id_organizacion, id_grupo, clave_componente, estado),
    CONSTRAINT chk_grupo_componente_ui_privilegio_clave_no_vacia CHECK (clave_componente <> ''),
    CONSTRAINT chk_grupo_componente_ui_privilegio_estado CHECK (estado IN ('VISIBLE', 'HABILITADO', 'EDITABLE'))
);

CREATE INDEX idx_grupo_componente_ui_privilegio_grupo ON grupo_componente_ui_privilegio(id_organizacion, id_grupo);
CREATE INDEX idx_grupo_componente_ui_privilegio_componente ON grupo_componente_ui_privilegio(clave_componente);
